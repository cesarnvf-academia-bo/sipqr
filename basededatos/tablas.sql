-- ODD-002 / ODD-003: Esquema SIPQR
-- Base de datos: sipprbd
-- Usuario: postgres

CREATE TABLE IF NOT EXISTS usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario VARCHAR(100) NOT NULL UNIQUE,
    clave VARCHAR(255) NOT NULL,
    estado BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_usuario_usuario ON usuario (usuario);
CREATE INDEX IF NOT EXISTS idx_usuario_estado ON usuario (estado);

CREATE TABLE IF NOT EXISTS configuracionqr (
    id SMALLINT PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    "userName" VARCHAR(150) NOT NULL CHECK (length(trim("userName")) > 0),
    "password" TEXT NOT NULL,
    keyencript TEXT NOT NULL,
    account TEXT NOT NULL,
    url TEXT NOT NULL CHECK (url ~ '^https://'),
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_configuracionqr_unica ON configuracionqr (id);

-- ODD-004: Idempotencia y trazabilidad de operaciones BANECO
CREATE TABLE IF NOT EXISTS baneco_operacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(40) NOT NULL,
    transaction_id VARCHAR(150),
    qr_id VARCHAR(100),
    batch_id VARCHAR(150),
    banco_batch_id BIGINT,
    estado VARCHAR(30) NOT NULL,
    codigo_respuesta INTEGER,
    mensaje_respuesta TEXT,
    hash_solicitud VARCHAR(128),
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_baneco_operacion_tipo_transaccion
    ON baneco_operacion (tipo, transaction_id)
    WHERE transaction_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_baneco_operacion_qr ON baneco_operacion (qr_id);
CREATE INDEX IF NOT EXISTS idx_baneco_operacion_batch ON baneco_operacion (batch_id);

-- ODD-004: Deduplicación de notificaciones recibidas
CREATE TABLE IF NOT EXISTS baneco_notificacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(40) NOT NULL,
    clave_evento VARCHAR(250) NOT NULL,
    hash_payload VARCHAR(128),
    estado VARCHAR(30) NOT NULL,
    fecha_recepcion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_procesamiento TIMESTAMPTZ,
    CONSTRAINT uq_baneco_notificacion_evento UNIQUE (tipo, clave_evento)
);

CREATE INDEX IF NOT EXISTS idx_baneco_notificacion_estado ON baneco_notificacion (estado);

-- ODD-004: Detalle de estados de lotes notificados
CREATE TABLE IF NOT EXISTS baneco_lote_detalle (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    banco_batch_id BIGINT,
    batch_id VARCHAR(150) NOT NULL,
    batch_detail_id VARCHAR(150) NOT NULL,
    estado VARCHAR(10) NOT NULL,
    descripcion_estado TEXT,
    transaction_id_debito VARCHAR(100),
    transaction_id_credito VARCHAR(100),
    fecha_recepcion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_baneco_lote_detalle UNIQUE (batch_id, batch_detail_id)
);

CREATE INDEX IF NOT EXISTS idx_baneco_lote_detalle_banco ON baneco_lote_detalle (banco_batch_id);

-- ODD-005: Pagos QR gestionados por SIPQR
CREATE TABLE IF NOT EXISTS pagosqr (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id VARCHAR(150) NOT NULL UNIQUE,
    qr_id VARCHAR(100) UNIQUE,
    amount NUMERIC(17, 2) NOT NULL CHECK (amount > 0),
    currency VARCHAR(3) NOT NULL CHECK (currency IN ('BOB', 'USD')),
    description VARCHAR(500),
    due_date DATE NOT NULL,
    single_use BOOLEAN NOT NULL DEFAULT TRUE,
    modify_amount BOOLEAN NOT NULL DEFAULT FALSE,
    branch_code VARCHAR(5),
    estado VARCHAR(20) NOT NULL DEFAULT 'REGISTRADO'
        CHECK (estado IN ('REGISTRADO', 'GENERANDO', 'PENDIENTE', 'PAGADO', 'ANULADO', 'VENCIDO', 'ERROR')),
    qr_image TEXT,
    response_code VARCHAR(50),
    response_message TEXT,
    resultado_incierto BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_ultima_verificacion TIMESTAMPTZ,
    fecha_pago TIMESTAMPTZ,
    fecha_anulacion TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_pagosqr_estado ON pagosqr (estado);
CREATE INDEX IF NOT EXISTS idx_pagosqr_fecha_creacion ON pagosqr (fecha_creacion);

CREATE TABLE IF NOT EXISTS pagosqr_detalle (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pagoqr_id BIGINT NOT NULL REFERENCES pagosqr (id) ON DELETE CASCADE,
    identificador_pago_bancario VARCHAR(150) NOT NULL,
    fecha_pago TIMESTAMPTZ,
    importe NUMERIC(17, 2) NOT NULL CHECK (importe > 0),
    moneda VARCHAR(3) NOT NULL,
    datos_pago JSONB NOT NULL,
    fecha_recepcion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_pagosqr_detalle_pago UNIQUE (pagoqr_id, identificador_pago_bancario)
);

CREATE INDEX IF NOT EXISTS idx_pagosqr_detalle_pago ON pagosqr_detalle (pagoqr_id);
